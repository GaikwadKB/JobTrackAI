 * Section 72 discussion points. Swapping in a custom `FontFamily` later is
 * a one-line change confined to this file — the same locality-of-change
 * argument as [Color.kt][JobTrackColors].
 *
 * Every text style in the app should come from `MaterialTheme.typography`,
